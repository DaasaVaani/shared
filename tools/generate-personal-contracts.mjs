import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import { strictYaml } from "./generate-catalog.mjs";

const root = fileURLToPath(new URL("../", import.meta.url));
const settingsSchema = JSON.parse(await readFile(resolve(root, "schemas/personal-transfer-settings.schema.json"), "utf8"));
const validateSettings = new Ajv2020({ strict: true }).compile(settingsSchema);
const backupSettingsSchema = JSON.parse(await readFile(resolve(root, "schemas/full-backup-settings.schema.json"), "utf8"));
const validateBackupSettings = new Ajv2020({ strict: true }).compile(backupSettingsSchema);

const uuid = () => ({
  type: "string",
  pattern: "^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$",
});
const legacyId = () => ({ type: "string", pattern: "^[A-Za-z0-9_-]{1,128}$" });
const comment = "Generated by tools/generate-personal-contracts.mjs from settings/personal-transfer.yml. Do not edit.";

export function personalReferenceSchema() {
  return {
    $schema: "https://json-schema.org/draft/2020-12/schema",
    $id: "https://daasavaani.github.io/contracts/personal-reference-v1.schema.json",
    $comment: comment,
    oneOf: [
      { type: "object", additionalProperties: false, required: ["kind", "lyricId"],
        properties: { kind: { const: "lyric" }, lyricId: uuid() } },
      { type: "object", additionalProperties: false, required: ["kind", "videoId"],
        properties: { kind: { const: "legacyVideo" }, videoId: legacyId() } },
    ],
  };
}

function validateLimits(settings) {
  if (!validateSettings(settings)) throw new Error("Invalid personal-transfer settings: " + JSON.stringify(validateSettings.errors));
  if (settings.maxEntriesPerList > settings.maxTotalEntries ||
      settings.maxListEncodedBytes <= settings.maxListDecodedBytes ||
      settings.maxBackupEncodedBytes <= settings.maxBackupDecodedBytes ||
      settings.maxPersonalStoredBytes > settings.maxBackupDecodedBytes) {
    throw new Error("Inconsistent personal-transfer collection or byte limits");
  }
}

export function recentHistorySchema(settings) {
  validateLimits(settings);
  return {
    $schema: "https://json-schema.org/draft/2020-12/schema",
    $id: "https://daasavaani.github.io/contracts/recent-history-v1.schema.json",
    $comment: comment,
    type: "object", additionalProperties: false, required: ["enabled", "entries"],
    properties: {
      enabled: { type: "boolean" },
      entries: { type: "array", maxItems: settings.maxRecents, uniqueItems: true,
        items: { oneOf: personalReferenceSchema().oneOf } },
    },
  };
}

export function learningLabelsSchema(settings) {
  validateLimits(settings);
  return {
    $schema: "https://json-schema.org/draft/2020-12/schema",
    $id: "https://daasavaani.github.io/contracts/learning-labels-v1.schema.json",
    $comment: comment,
    type: "object", additionalProperties: false, required: ["entries"],
    properties: {
      entries: { type: "array", maxItems: settings.maxLearningLabels,
        items: { oneOf: personalReferenceSchema().oneOf.map(reference => ({
          ...reference, required: [...reference.required, "label"],
          properties: { ...reference.properties,
            label: { enum: ["wantToLearn", "practising", "comfortableReciting"] } },
        })) } },
    },
  };
}

export function recitationPositionSchema() {
  return {
    $schema: "https://json-schema.org/draft/2020-12/schema",
    $id: "https://daasavaani.github.io/contracts/recitation-position-v1.schema.json",
    $comment: comment,
    type: "object", additionalProperties: false, required: ["position"],
    properties: {
      position: {
        oneOf: [
          { type: "null" },
          { type: "object", additionalProperties: false, required: ["listId", "entryId"],
            properties: { listId: uuid(), entryId: uuid() } },
        ],
      },
    },
  };
}

export function listTransferSchema(settings, version = 1) {
  if (version !== 1 && version !== 2) throw new Error("Unsupported list contract version");
  validateLimits(settings);
  const singleLine = maxLength => ({
    type: "string", minLength: 1, maxLength,
    pattern: "^[^\\u0000-\\u001f\\u007f-\\u009f\\u2028\\u2029\\ud800-\\udfff]*$",
  });
  return {
    $schema: "https://json-schema.org/draft/2020-12/schema",
    $id: `https://daasavaani.github.io/contracts/list-transfer-v${version}.schema.json`,
    $comment: comment,
    type: "object", additionalProperties: false,
    required: ["format", "formatVersion", "name", "entries"],
    properties: {
      format: { const: "daasavaani-list" },
      formatVersion: { const: version },
      name: singleLine(settings.maxListNameCodePoints),
      entries: {
        type: "array", maxItems: settings.maxEntriesPerList,
        items: {
          oneOf: [
            ...(version === 1 ? [{
              type: "object", additionalProperties: false, required: ["kind", "videoId"],
              properties: {
                kind: { const: "item" },
                videoId: legacyId(),
                fallback: singleLine(settings.maxEntryTextCodePoints),
              },
            }] : personalReferenceSchema().oneOf.map(reference => ({
              ...reference,
              properties: { ...reference.properties, fallback: singleLine(settings.maxEntryTextCodePoints) },
            }))),
            {
              type: "object", additionalProperties: false, required: ["kind", "text"],
              properties: { kind: { const: "placeholder" }, text: singleLine(settings.maxEntryTextCodePoints) },
            },
          ],
        },
      },
    },
  };
}

export function listRecordSchema(settings, version = 1) {
  const transfer = listTransferSchema(settings, version);
  const identity = uuid();
  return {
    $schema: transfer.$schema,
    $id: `https://daasavaani.github.io/contracts/list-record-v${version}.schema.json`,
    $comment: transfer.$comment,
    type: "object", additionalProperties: false,
    required: ["id", "name", "entries"],
    properties: {
      id: identity,
      name: transfer.properties.name,
      entries: {
        ...transfer.properties.entries,
        items: {
          oneOf: transfer.properties.entries.items.oneOf.map(entry => ({
            ...entry,
            required: ["id", ...entry.required],
            properties: { id: identity, ...entry.properties },
          })),
        },
      },
    },
  };
}

export function fullBackupSchema(settings, profiles) {
  validateLimits(settings);
  if (!validateBackupSettings(profiles)) throw new Error("Invalid full-backup settings");
  for (const [platform, model, unit] of [["web", "webv8", "cssPx"], ["android", "nativeRoom7", "sp"]]) {
    const profile = profiles[platform];
    if (profile.sourceModel !== model || profile.fontUnit !== unit ||
        profile.fontMin > profile.fontMax || profile.fontStep > profile.fontMax - profile.fontMin ||
        profile.fontMin % profile.fontStep !== 0 ||
        (profile.fontMax - profile.fontMin) % profile.fontStep !== 0) throw new Error("Inconsistent full-backup profile");
  }
  const embedded = ({ $schema, $id, $comment, ...shape }) => shape;
  const object = properties => ({ type: "object", additionalProperties: false,
    required: Object.keys(properties), properties });
  const references = maxItems => ({ type: "array", maxItems,
    items: { oneOf: personalReferenceSchema().oneOf } });
  const choice = enumValues => ({ enum: enumValues });
  return {
    $schema: "https://json-schema.org/draft/2020-12/schema",
    $id: "https://daasavaani.github.io/contracts/full-personal-backup-v1.schema.json",
    $comment: comment + " Platform profiles: settings/full-backup.yml.",
    oneOf: ["web", "android"].map(platform => {
      const profile = profiles[platform];
      const preferences = object({
        language: choice(platform === "web" ? ["en", "kn"] : ["device", "en", "kn"]),
        theme: choice(["light", "dark", "warm", "device"]),
        [platform === "web" ? "fontSizePx" : "lyricFontSizeSp"]: {
          type: "integer", minimum: profile.fontMin, maximum: profile.fontMax, multipleOf: profile.fontStep,
        },
        [platform === "web" ? "density" : "readingDensity"]: choice(["compact", "normal", "relaxed"]),
      });
      const data = object({
        preferences: platform === "web" ? { oneOf: [{ type: "null" }, preferences] } : preferences,
        favorites: references(settings.maxFavorites),
        lists: { type: "array", maxItems: settings.maxLists, items: embedded(listRecordSchema(settings, 2)) },
        [platform === "web" ? "history" : "recentHistory"]: embedded(recentHistorySchema(settings)),
        learning: embedded(learningLabelsSchema(settings)),
        recitation: embedded(recitationPositionSchema()),
      });
      if (platform === "web") data.allOf = [{
        if: { properties: { preferences: { type: "null" } } },
        then: { properties: { favorites: { type: "array", maxItems: 0 } } },
      }];
      return object({
        format: { const: "daasavaani-personal-backup" },
        formatVersion: { const: 1 },
        platform: { const: platform },
        exportedAt: { type: "string", pattern: "^[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}:[0-9]{2}\\.[0-9]{3}Z$" },
        data,
      });
    }),
  };
}

export async function generatePersonalContracts() {
  const settings = strictYaml(await readFile(resolve(root, "settings/personal-transfer.yml"), "utf8"));
  const profiles = strictYaml(await readFile(resolve(root, "settings/full-backup.yml"), "utf8"));
  await writeFile(resolve(root, "schemas/list-transfer.schema.json"), JSON.stringify(listTransferSchema(settings), null, 2) + "\n");
  await writeFile(resolve(root, "schemas/list-record.schema.json"), JSON.stringify(listRecordSchema(settings), null, 2) + "\n");
  await writeFile(resolve(root, "schemas/personal-reference.schema.json"), JSON.stringify(personalReferenceSchema(), null, 2) + "\n");
  await writeFile(resolve(root, "schemas/list-transfer-v2.schema.json"), JSON.stringify(listTransferSchema(settings, 2), null, 2) + "\n");
  await writeFile(resolve(root, "schemas/list-record-v2.schema.json"), JSON.stringify(listRecordSchema(settings, 2), null, 2) + "\n");
  await writeFile(resolve(root, "schemas/recent-history.schema.json"), JSON.stringify(recentHistorySchema(settings), null, 2) + "\n");
  await writeFile(resolve(root, "schemas/learning-labels.schema.json"), JSON.stringify(learningLabelsSchema(settings), null, 2) + "\n");
  await writeFile(resolve(root, "schemas/recitation-position.schema.json"), JSON.stringify(recitationPositionSchema(), null, 2) + "\n");
  await writeFile(resolve(root, "schemas/full-personal-backup.schema.json"), JSON.stringify(fullBackupSchema(settings, profiles), null, 2) + "\n");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await generatePersonalContracts();
