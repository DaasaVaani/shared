import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import { strictYaml } from "./generate-catalog.mjs";

const root = fileURLToPath(new URL("../", import.meta.url));
const settingsSchema = JSON.parse(await readFile(resolve(root, "schemas/personal-transfer-settings.schema.json"), "utf8"));
const validateSettings = new Ajv2020({ strict: true }).compile(settingsSchema);

export function listTransferSchema(settings) {
  if (!validateSettings(settings)) throw new Error("Invalid personal-transfer settings: " + JSON.stringify(validateSettings.errors));
  if (settings.maxEntriesPerList > settings.maxTotalEntries ||
      settings.maxListEncodedBytes <= settings.maxListDecodedBytes ||
      settings.maxBackupEncodedBytes <= settings.maxBackupDecodedBytes) {
    throw new Error("Inconsistent personal-transfer collection or byte limits");
  }
  const singleLine = maxLength => ({
    type: "string", minLength: 1, maxLength,
    pattern: "^[^\\u0000-\\u001f\\u007f-\\u009f\\u2028\\u2029\\ud800-\\udfff]*$",
  });
  return {
    $schema: "https://json-schema.org/draft/2020-12/schema",
    $id: "https://daasavaani.github.io/contracts/list-transfer-v1.schema.json",
    $comment: "Generated by tools/generate-personal-contracts.mjs from settings/personal-transfer.yml. Do not edit.",
    type: "object", additionalProperties: false,
    required: ["format", "formatVersion", "name", "entries"],
    properties: {
      format: { const: "daasavaani-list" },
      formatVersion: { const: 1 },
      name: singleLine(settings.maxListNameCodePoints),
      entries: {
        type: "array", maxItems: settings.maxEntriesPerList,
        items: {
          oneOf: [
            {
              type: "object", additionalProperties: false, required: ["kind", "videoId"],
              properties: {
                kind: { const: "item" },
                videoId: { type: "string", pattern: "^[A-Za-z0-9_-]{1,128}$" },
                fallback: singleLine(settings.maxEntryTextCodePoints),
              },
            },
            {
              type: "object", additionalProperties: false, required: ["kind", "text"],
              properties: { kind: { const: "placeholder" }, text: singleLine(settings.maxEntryTextCodePoints) },
            },
          ],
        },
      },
    },
  };
}

export function listRecordSchema(settings) {
  const transfer = listTransferSchema(settings);
  const uuid = {
    type: "string",
    pattern: "^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$",
  };
  return {
    $schema: transfer.$schema,
    $id: "https://daasavaani.github.io/contracts/list-record-v1.schema.json",
    $comment: transfer.$comment,
    type: "object", additionalProperties: false,
    required: ["id", "name", "entries"],
    properties: {
      id: uuid,
      name: transfer.properties.name,
      entries: {
        ...transfer.properties.entries,
        items: {
          oneOf: transfer.properties.entries.items.oneOf.map(entry => ({
            ...entry,
            required: ["id", ...entry.required],
            properties: { id: uuid, ...entry.properties },
          })),
        },
      },
    },
  };
}

export async function generatePersonalContracts() {
  const settings = strictYaml(await readFile(resolve(root, "settings/personal-transfer.yml"), "utf8"));
  await writeFile(resolve(root, "schemas/list-transfer.schema.json"), JSON.stringify(listTransferSchema(settings), null, 2) + "\n");
  await writeFile(resolve(root, "schemas/list-record.schema.json"), JSON.stringify(listRecordSchema(settings), null, 2) + "\n");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await generatePersonalContracts();
