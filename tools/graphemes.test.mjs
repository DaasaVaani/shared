test("real pinned segmentation feeds the actual excerpt selector without splitting emoji/decomposed clusters", () => {
  const literal = "a".repeat(230) + "\u{1f469}\u{1f3fd}\u200d\u{1f4bb}e\u0301" + "b".repeat(20);
  const boundaries = reference.boundaries(literal), length = [...literal].length;
  const result = selectExcerptWindow({ termCount: 1, codePointLength: length, graphemeBoundaries: boundaries,
    matches: [{ term: 0, edits: 0, ranges: [[231, 232], [235, 236]] }] }, policy);
  assert.equal(result.status, "ready");
  assert.ok(boundaries.includes(result.start) && boundaries.includes(result.end));
  const rendered = (result.leadingEllipsis ? "\u2026" : "") + [...literal].slice(result.start, result.end).join("") +
    (result.trailingEllipsis ? "\u2026" : "");
  assert.equal([...rendered].length, result.renderedCodePoints);
  assert.equal(result.renderedCodePoints, 240);
  assert.ok(rendered.includes("\u{1f469}\u{1f3fd}\u200d\u{1f4bb}e\u0301"));
  const huge = "a" + "\u0301".repeat(300);
  assert.deepEqual(reference.boundaries(huge), [0, 301]);
  assert.equal(selectExcerptWindow({ termCount: 1, codePointLength: 301, graphemeBoundaries: reference.boundaries(huge),
    matches: [{ term: 0, edits: 0, ranges: [[0, 1]] }] }, policy).status, "unavailable");
});
