const policy = { maxTerms: search.maxTerms, maxExcerptCodePoints: search.maxExcerptCodePoints };

test("independent approved profile, immutable licensed source identities and generated bytes are reproducible", async () => {
  assert.equal(settings.profile, "unicode16-extended-graphemes-v1");
  assert.equal(settings.algorithm, "uax29-45-extended");
  assert.equal(bytes.toString("utf8"), JSON.stringify(buildGraphemeData(settings, sources)) + "\n");
  assert.equal(bytes.length, 40352);
  assert.deepEqual([data.graphemeBreakRanges.length, data.extendedPictographicRanges.length, data.indicConjunctRanges.length], [1376, 78, 403]);
  for (const [name, metadata] of Object.entries(settings.sources)) {
    assert.equal(sha256(Buffer.from(sources[name])), metadata.sha256);
    assert.throws(() => verifyUnicodeSource(name, metadata, Buffer.from(sources[name] + "\n")), /SHA-256 mismatch/);
    assert.doesNotMatch(sources[name], /\r/);
  }
  const license = await readFile(new URL("../" + settings.license.path, import.meta.url));
  assert.equal(sha256(license), settings.license.sha256);
  const manifest = JSON.parse(await readFile(new URL("../generated/graphemes/manifest.json", import.meta.url), "utf8"));
  assert.deepEqual(manifest.data, { path: "unicode16.json", bytes: bytes.length, sha256: sha256(bytes) });
  const officialTests = Buffer.from(sources["GraphemeBreakTest.txt"]);
  assert.deepEqual(manifest.conformance, { path: "resources/graphemes16/GraphemeBreakTest.txt",
    bytes: officialTests.length, sha256: sha256(officialTests) });
  assert.deepEqual(manifest.license, settings.license);
  assert.throws(() => verifyUnicodeSource("generated graphemes", manifest.data, Buffer.from(bytes.toString("utf8") + " ")), /SHA-256 mismatch/);
});
test("all1093 official Unicode16 GraphemeBreakTest rows match exact code-point boundaries", () => {
  let rows = 0;
  for (const line of sources["GraphemeBreakTest.txt"].split("\n")) {
    const body = line.split("#")[0].trim();
    if (!body) continue;
    const points = [], expected = [];
    for (const token of body.split(/\s+/)) {
      if (token === "\u00f7") expected.push(points.length);
      else if (token !== "\u00d7") {
        assert.match(token, /^[0-9A-F]{4,6}$/);
        points.push(parseInt(token, 16));
      }
    }
    assert.deepEqual(reference.boundaries(text(points)), expected, `official row ${++rows}`);
  }
  assert.equal(rows, 1093);
});
test("generated merged property tables equal independent original UCD assignments over all1114112 code points", () => {
  function original(name, select) {
    const result = new Map();
    for (const line of sources[name].split("\n")) {
      const body = line.split("#")[0].trim();
      if (!body) continue;
      const columns = body.split(";").map(value => value.trim()), value = select(columns);
      if (value === undefined) continue;
      const [start, end = start] = columns[0].split("..").map(value => parseInt(value, 16));
      for (let cp = start; cp <= end; cp++) { assert.equal(result.has(cp), false); result.set(cp, value); }
    }
    return result;
  }
  const expected = [
    original("GraphemeBreakProperty.txt", row => row[1]),
    original("emoji-data.txt", row => row[1] === "Extended_Pictographic" ? true : undefined),
    original("DerivedCoreProperties.txt", row => row[1] === "InCB" ? row[2] : undefined)
  ];
  const actual = [data.graphemeBreakRanges, data.extendedPictographicRanges, data.indicConjunctRanges].map(rows => {
    const result = new Map();
    for (const [start, end, value = true] of rows) for (let cp = start; cp <= end; cp++) result.set(cp, value);
    return result;
  });
  for (let cp = 0; cp <= 0x10ffff; cp++) for (let property = 0; property < 3; property++) {
    assert.equal(actual[property].get(cp), expected[property].get(cp), `property ${property} U+${cp.toString(16)}`);
  }
});
